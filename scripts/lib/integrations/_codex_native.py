"""Codex-native agent and hook materialization (v3.15.8 Phase 5).

Codex reads two surfaces that no other Nexus-Hub platform reads in the same
shape, and neither is a verbatim copy of the catalog:

  - **Custom agents** are standalone TOML files under ``~/.codex/agents/`` and
    ``<project>/.codex/agents/``. Every file must define ``name``,
    ``description``, and ``developer_instructions``; ``model``,
    ``model_reasoning_effort``, ``sandbox_mode``, ``mcp_servers``, and
    ``skills.config`` are optional. The catalog ships Markdown agents with
    ``name`` / ``description`` / ``tools`` frontmatter, so this module transforms
    rather than copies.
  - **Hooks** are registered in ``hooks.json`` next to an active config layer
    (``~/.codex/hooks.json``, ``<project>/.codex/hooks.json``). Codex's event
    names line up with the ones Nexus-Hub already uses in
    ``catalog/hooks/settings.json``, but its ``matcher`` vocabulary does not:
    only ``Bash``, ``apply_patch`` (aliases ``Edit`` / ``Write``), MCP tool
    names, and other local function tools are recognized. Matchers with no
    Codex equivalent are dropped rather than guessed at.

Two Codex behaviors shape the design.

``hooks.json`` is a shared file: a user may already have their own hooks in it,
and Codex loads every hook source additively. So this module performs a
structured merge keyed on ownership rather than writing the file wholesale.
A handler is Nexus-Hub-owned when its command references the hooks directory
this integration installs into; nothing else is touched, and teardown removes
only owned handlers.

Each handler may carry ``commandWindows``, an official Windows-only command
override. That maps exactly onto Nexus-Hub's ``.sh`` / ``.ps1`` sibling
convention: the POSIX command goes in ``command`` and the PowerShell sibling in
``commandWindows``, so a Windows user gets the same guardrail from the same
registration instead of a silently absent one.

This module is stdlib-only and makes no outbound calls.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from ._catalog_adapters import _split_frontmatter
from ._hooks_common import script_basename, sourced_modules, strip_owned_handlers
from ._owned import write_owned_file
from .base import IntegrationBase
from .result import FileAction

# Codex hook events, per the official hooks reference. Nexus-Hub only emits the
# subset that catalog/hooks/settings.json actually registers; the rest are listed
# so a future settings.json event is validated rather than silently dropped.
CODEX_HOOK_EVENTS = frozenset(
    {
        "SessionStart",
        "SessionEnd",
        "PreToolUse",
        "PermissionRequest",
        "PostToolUse",
        "PreCompact",
        "PostCompact",
        "UserPromptSubmit",
        "SubagentStart",
        "SubagentStop",
        "Stop",
    }
)

# Codex ignores any configured matcher for these events, so emitting one would
# be noise that implies filtering Codex does not perform.
CODEX_MATCHERLESS_EVENTS = frozenset({"UserPromptSubmit", "Stop"})

# Claude-style event names Codex implements under a DIFFERENT name. Without an
# alias the chain is dropped for want of a same-named event, which is how
# Nexus-Hub's Notification chain (the "agent is blocked on the human" trigger)
# silently failed to reach Codex.
#
# Verified 2026-08-04 against the Codex implementation itself rather than prose
# docs, because openai/codex ships no docs/hooks.md: `codex-rs/hooks/src/events/`
# contains a dedicated `permission_request.rs` module, and the serde wire names in
# `codex-rs/hooks/src/lib.rs` enumerate PermissionRequest alongside Stop. That
# makes Codex the only platform besides Claude Code able to express the
# attention-required trigger.
CODEX_EVENT_ALIASES = {"Notification": "PermissionRequest"}


# Tool-name matcher tokens Codex recognizes for PreToolUse / PostToolUse.
# `apply_patch` is the canonical name for file edits; `Edit` and `Write` are its
# documented aliases. Nexus-Hub's `PowerShell`, `MultiEdit`, and `Skill` tokens
# have no Codex equivalent -- Codex routes every shell call through `Bash` -- so
# they are dropped instead of being mapped onto an approximation.
CODEX_TOOL_MATCHERS = frozenset({"Bash", "apply_patch", "Edit", "Write"})

# Tools that cannot mutate the workspace. An agent whose catalog `tools` list is
# entirely within this set is emitted with `sandbox_mode = "read-only"`, which
# constrains the agent rather than widening it: the inference can only ever fail
# closed. Any unrecognized tool leaves sandbox_mode unset so the agent inherits
# the parent session.
_READ_ONLY_TOOLS = frozenset(
    {"read", "glob", "grep", "ls", "webfetch", "websearch", "notebookread"}
)

_GENERATED_HEADER = (
    "# Generated by Nexus-Hub from {source}. Do not edit by hand.\n"
    "# Re-run the installer to refresh; local edits are replaced on upgrade.\n"
)


# ----- TOML emission ------------------------------------------------------


def _toml_basic_string(value: str) -> str:
    """Return ``value`` as a single-line TOML basic string."""
    collapsed = " ".join(value.split())
    escaped = collapsed.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
    return f'"{escaped}"'


def _toml_multiline_string(value: str) -> str:
    """Return ``value`` as a TOML multi-line string.

    Prefers a literal (``'''``) string so the agent body stays readable in the
    generated file, since literals need no escaping at all. Falls back to a
    basic (``\"\"\"``) string with full escaping when the body contains ``'''``
    or ends in a quote, which a literal cannot represent.
    """
    text = value.replace("\r\n", "\n").replace("\r", "\n").strip("\n")
    if "'''" not in text and not text.endswith("'"):
        return f"'''\n{text}\n'''"
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if escaped.endswith('"'):
        escaped = escaped[:-1] + '\\"'
    return f'"""\n{escaped}\n"""'


def infer_sandbox_mode(tools_field: str) -> str | None:
    """Return ``"read-only"`` when every listed catalog tool is non-mutating.

    Codex has no equivalent of the catalog's ``tools`` allowlist, so the field
    cannot be carried across verbatim. Rather than drop the intent entirely, an
    agent that the catalog already restricts to read-only tools is sandboxed
    read-only in Codex. An empty list, or any tool outside the known read-only
    set, yields ``None`` (inherit from the parent session).
    """
    tools = [item.strip() for item in tools_field.split(",") if item.strip()]
    if not tools:
        return None
    if all(tool.lower() in _READ_ONLY_TOOLS for tool in tools):
        return "read-only"
    return None


def render_agent_toml(source_name: str, markdown: str) -> bytes | None:
    """Transform one ``catalog/agents/<name>.md`` into a Codex agent TOML file.

    Returns ``None`` when the source lacks the fields Codex requires, so the
    caller can skip it rather than emit a file Codex will reject at load time.
    """
    meta, body = _split_frontmatter(markdown)
    name = meta.get("name", "").strip() or source_name
    description = meta.get("description", "").strip()
    instructions = body.strip()
    if not description or not instructions:
        return None

    lines = [_GENERATED_HEADER.format(source=f"catalog/agents/{source_name}.md")]
    tools = meta.get("tools", "").strip()
    if tools:
        lines.append(f"# Catalog tools: {tools}\n")
    lines.append(f"name = {_toml_basic_string(name)}\n")
    lines.append(f"description = {_toml_basic_string(description)}\n")
    sandbox_mode = infer_sandbox_mode(tools)
    if sandbox_mode:
        lines.append(f"sandbox_mode = {_toml_basic_string(sandbox_mode)}\n")
    lines.append(f"developer_instructions = {_toml_multiline_string(instructions)}\n")
    return "".join(lines).encode("utf-8")


