# `write_owned_file` moved to `_owned` in Phase 7, when Kimi needed the same
# manifest-aware write. Re-exported here so this module's public surface (and the
# Phase 5 tests that import it) is unchanged.


def agents_to_codex_toml(
    ctx, key: str, src_agents_dir: Path, dst_agents_dir: Path
) -> list[FileAction]:
    """Materialize ``catalog/agents/*.md`` as Codex custom-agent TOML files."""
    if not src_agents_dir.exists():
        ctx.manifest.log(key, f"missing-tree: {src_agents_dir}")
        return [FileAction(path=str(src_agents_dir), action="not-found")]
    IntegrationBase._ensure_dir(dst_agents_dir, ctx)
    actions: list[FileAction] = []
    for md in sorted(src_agents_dir.glob("*.md")):
        content = render_agent_toml(md.stem, md.read_text(encoding="utf-8"))
        if content is None:
            ctx.manifest.log(key, f"skip agent (missing required fields): {md.name}")
            continue
        actions.append(
            write_owned_file(ctx, key, dst_agents_dir / f"{md.stem}.toml", content)
        )
    return actions


# ----- hook registration --------------------------------------------------


def _normalize_matcher(event: str, matcher: str) -> str | None:
    """Map a Nexus-Hub matcher onto Codex's matcher vocabulary.

    Returns ``None`` when no alternative survives, meaning the group has no
    Codex equivalent and must be skipped. Returns ``""`` when the event takes no
    matcher (or the source matcher was already empty), meaning "match all".
    """
    if event in CODEX_MATCHERLESS_EVENTS:
        return ""
    matcher = matcher.strip()
    if not matcher:
        return ""
    supported = [
        part for part in matcher.split("|") if part.strip() in CODEX_TOOL_MATCHERS
    ]
    if not supported:
        return None
    return "|".join(supported)


def _split_command(command: str) -> tuple[str, str] | None:
    """Split a catalog hook command into (runner, script).

    Codex is the only adapter that needs the runner as well as the script, to
    preserve ``python3`` vs ``python`` for a ``.py`` hook, so it keeps this thin
    wrapper over the shared ``script_basename``.
    """
    parts = command.split()
    script = script_basename(command)
    if script is None:
        return None
    return parts[0], script


def build_hook_entries(
    settings: dict, src_hooks_dir: Path, command_base: str
) -> tuple[dict, set[str], list[str]]:
    """Build Codex hook groups from ``catalog/hooks/settings.json``.

    Returns ``(events, scripts, skipped)`` where ``events`` is the ``hooks``
    mapping to merge into ``hooks.json``, ``scripts`` is every catalog file that
    must be copied alongside it (including ``.ps1`` siblings), and ``skipped``
    describes each group dropped for want of a Codex equivalent.
    """
    events: dict[str, list] = {}
    scripts: set[str] = set()
    skipped: list[str] = []

    for event, groups in settings.get("hooks", {}).items():
        # Resolve a Claude-style name onto Codex's own name before the membership
        # test, or an aliased chain is dropped as "no Codex event of that name".
        event = CODEX_EVENT_ALIASES.get(event, event)
        if event not in CODEX_HOOK_EVENTS:
            skipped.append(f"{event}: no Codex event of that name")
            continue
        for group in groups:
            matcher = _normalize_matcher(event, group.get("matcher", ""))
            if matcher is None:
                skipped.append(
                    f"{event}/{group.get('matcher', '')}: no Codex matcher equivalent"
                )
                continue
            handlers: list[dict] = []
            for handler in group.get("hooks", []):
                split = _split_command(handler.get("command", ""))
                if split is None:
                    continue
                runner, script = split
                if not (src_hooks_dir / script).exists():
                    skipped.append(
                        f"{event}/{script}: script absent from catalog/hooks"
                    )
                    continue
                scripts.add(script)
                entry: dict[str, object] = {"type": "command"}
                if script.endswith(".py"):
                    entry["command"] = f"{runner} {command_base}/{script}"
                    entry["commandWindows"] = f"python {command_base}/{script}"
                else:
                    entry["command"] = f"bash {command_base}/{script}"
                    sibling = f"{Path(script).stem}.ps1"
                    if (src_hooks_dir / sibling).exists():
                        scripts.add(sibling)
                        entry["commandWindows"] = (
                            "powershell -NoProfile -ExecutionPolicy Bypass "
                            f"-File {command_base}/{sibling}"
                        )
                entry["statusMessage"] = f"Nexus-Hub {Path(script).stem}"
                handlers.append(entry)
            if not handlers:
                continue
            emitted: dict[str, object] = {}
            if matcher:
                emitted["matcher"] = matcher
            emitted["hooks"] = handlers
            events.setdefault(event, []).append(emitted)

    # Shared modules are not registered anywhere, so they must be resolved from
    # the delivered script bodies. Without this a hook that sources one is copied
    # and registered but exits silently on every run.
    scripts |= sourced_modules(scripts, src_hooks_dir)

    return events, scripts, skipped


def merge_hooks_json(
    ctx, key: str, dst: Path, owned_events: dict, owned_base: str
) -> FileAction:
    """Merge Nexus-Hub hook groups into ``hooks.json``, preserving user entries.

    A malformed existing file is never overwritten: Codex would lose the user's
    hooks, and the parse failure is more likely to be a transient local edit than
    something the installer should resolve. The file is kept and the reason
    logged. A successful merge writes atomically through a temp file, so a
    failure part-way leaves the original intact, and backs the previous content
    up next to the file before the first mutation.
    """
    existing: dict = {}
    if dst.exists():
        raw = dst.read_text(encoding="utf-8")
        try:
            parsed = json.loads(raw) if raw.strip() else {}
        except json.JSONDecodeError as exc:
            ctx.manifest.log(key, f"skip-malformed-json: {dst} ({exc})")
            return FileAction(path=str(dst), action="kept")
        if not isinstance(parsed, dict):
            ctx.manifest.log(key, f"skip-non-object-json: {dst}")
            return FileAction(path=str(dst), action="kept")
        existing = parsed

    merged = dict(existing)
    hooks = dict(merged.get("hooks") or {})
    for event in list(hooks):
        hooks[event] = strip_owned_handlers(list(hooks[event] or []), owned_base)
    for event, groups in owned_events.items():
        hooks[event] = list(hooks.get(event) or []) + list(groups)
    merged["hooks"] = {event: groups for event, groups in hooks.items() if groups}

    content = (json.dumps(merged, indent=2) + "\n").encode("utf-8")
    if dst.exists() and dst.read_bytes() == content:
        ctx.manifest.track(key, str(dst))
        return FileAction(path=str(dst), action="unchanged")

    existed = dst.exists()
    if not ctx.dry_run:
        dst.parent.mkdir(parents=True, exist_ok=True)
        if existed:
            backup = dst.with_suffix(dst.suffix + ".nexus-hub.bak")
            backup.write_bytes(dst.read_bytes())
            ctx.manifest.track(key, str(backup))
        tmp = dst.with_suffix(dst.suffix + ".nexus-hub.tmp")
        tmp.write_bytes(content)
        os.replace(tmp, dst)
    ctx.manifest.track(key, str(dst))
    return FileAction(path=str(dst), action="updated" if existed else "created")


def prune_hooks_json(dst: Path, owned_base: str, dry_run: bool) -> FileAction:
    """Remove Nexus-Hub handlers from ``hooks.json`` during teardown.

    The file is deleted only when nothing but our own entries remained; a file
    that still holds user hooks is rewritten without ours.
    """
    if not dst.exists():
        return FileAction(path=str(dst), action="not-found")
    try:
        parsed = json.loads(dst.read_text(encoding="utf-8") or "{}")
    except json.JSONDecodeError:
        return FileAction(path=str(dst), action="kept")
    if not isinstance(parsed, dict):
        return FileAction(path=str(dst), action="kept")

    hooks = dict(parsed.get("hooks") or {})
    for event in list(hooks):
        survivors = strip_owned_handlers(list(hooks[event] or []), owned_base)
        if survivors:
            hooks[event] = survivors
        else:
            del hooks[event]

    remainder = {k: v for k, v in parsed.items() if k != "hooks"}
    if not hooks and not remainder:
        if not dry_run:
            dst.unlink(missing_ok=True)
        return FileAction(path=str(dst), action="removed")

    remainder["hooks"] = hooks
    content = (json.dumps(remainder, indent=2) + "\n").encode("utf-8")
    if dst.read_bytes() == content:
        return FileAction(path=str(dst), action="unchanged")
    if not dry_run:
        dst.write_bytes(content)
    return FileAction(path=str(dst), action="updated")


